CREATE TABLE CATEGORIA
(
	ID SMALLINT NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(60) NOT NULL ,
    IDCATEGORIA SMALLINT ,
	FOREIGN KEY (IDCATEGORIA) REFERENCES CATEGORIA(ID)
		ON UPDATE CASCADE
        ON DELETE NO ACTION
);
CREATE TABLE MARCA
(
	ID SMALLINT NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(60) NOT NULL 
);
CREATE TABLE PRODUCTO
(
	CODIGO VARCHAR(4) NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(60) NOT NULL ,
    PRECIO FLOAT NOT NULL,
    IDCATEGORIA SMALLINT NOT NULL,
    IDMARCA SMALLINT NOT NULL,
	FOREIGN KEY (IDCATEGORIA) REFERENCES CATEGORIA(ID)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
	FOREIGN  KEY (IDMARCA) REFERENCES MARCA(ID)
		ON UPDATE CASCADE
        ON DELETE CASCADE	
);
CREATE TABLE TIPOPAGO
(
	ID TINYINT NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(60) NOT NULL 
);
CREATE TABLE PERSONA
(
	CI INT NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL ,
    TELEFONO INT,
    CARGO VARCHAR(30),
    DIRECCION VARCHAR(60),
    CORREO VARCHAR(50),
    TIPOE CHAR NOT NULL,
    TIPOC CHAR NOT NULL
);

CREATE TABLE NOTAVENTA
(
	NRO INT NOT NULL PRIMARY KEY,
    FECHA DATE NOT NULL ,
	MONTOTOTAL FLOAT NOT NULL,
	PLAZO TINYINT NOT NULL,
	CICLIENTE INT NOT NULL,
    CIENCARGADO INT NOT NULL,    /*SER CUIDADOSO CON EL ORDEN */
    IDTIPOPAGO TINYINT NOT NULL,
	FOREIGN  KEY (CICLIENTE) REFERENCES PERSONA(CI)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
	FOREIGN  KEY (CIENCARGADO) REFERENCES PERSONA(CI)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
	FOREIGN KEY (IDTIPOPAGO) REFERENCES TIPOPAGO(ID)
		ON UPDATE CASCADE
        ON DELETE CASCADE
);
CREATE TABLE FACTURA
(
	NRO INT NOT NULL PRIMARY KEY,
    FECHA DATE NOT NULL ,
	MONTO FLOAT NOT NULL,
	NIT INT NOT NULL,
    NOMBRE VARCHAR(60) NOT NULL 
);
CREATE TABLE CUOTA
(
	NRONOTAVENTA INT NOT NULL,
	NROCU TINYINT NOT NULL,
    FECHA DATE NOT NULL ,
	MONTO FLOAT NOT NULL,
    NROFACTURA INT ,
    PRIMARY KEY (NRONOTAVENTA,NROCU),
    FOREIGN KEY (NRONOTAVENTA) REFERENCES NOTAVENTA(NRO)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
	FOREIGN KEY (NROFACTURA) REFERENCES FACTURA(NRO)
		ON UPDATE CASCADE
        ON DELETE CASCADE	
);
CREATE TABLE DETALLEVENTA
(
	NRONOTAVENTA INT NOT NULL,
	ID SMALLINT NOT NULL,
	CANTIDAD INT NOT NULL,
    PRECIOUNITARIO FLOAT NOT NULL,
    CODIGOPRODUCTO VARCHAR(4) NOT NULL,
    PRIMARY KEY (NRONOTAVENTA, ID),
    FOREIGN KEY (NRONOTAVENTA) REFERENCES NOTAVENTA(NRO)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
	FOREIGN KEY (CODIGOPRODUCTO) REFERENCES PRODUCTO(CODIGO)
		ON UPDATE CASCADE
        ON DELETE CASCADE	
);

