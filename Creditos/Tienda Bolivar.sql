/* Mostrar todos los productos que pertenecen a la categoria Aspirado Limpieza */
SELECT *
FROM PRODUCTO
WHERE PRODUCTO.IDCATEGORIA IN	(	SELECT ID
									FROM CATEGORIA
									WHERE IDCATEGORIA =	(	SELECT CATEGORIA.ID
															FROM CATEGORIA
															WHERE CATEGORIA.NOMBRE= 'ASPIRADO LIMPIEZA')
								);
/* Mostrar todas las notas de ventas de los que son solo clientes */
SELECT * 
FROM NOTAVENTA
WHERE CICLIENTE IN (SELECT CI
					FROM PERSONA
					WHERE TIPOE='F' AND TIPOC='v');
                    
/* MOSTRAR TODAS LAS CUOTAS QUE NO HAN SIDO PAGADAS */
SELECT *
FROM CUOTA
WHERE NROFACTURA IS NULL;

/* MOSTRAR LA DEUDA EXISTENTE HASTA LA ACTUALIDAD POR CADA NOTA DE VENTA*/
SELECT NRONOTAVENTA, CICLIENTE, SUM(MONTO)
FROM CUOTA,NOTAVENTA
WHERE NROFACTURA IS NULL AND (CUOTA.NRONOTAVENTA = NOTAVENTA.NRO) GROUP BY NRONOTAVENTA;

/* MOSTRAR LOS PRODUCTOS QUE NO SE HAN VENDIDO */
SELECT PRODUCTO.NOMBRE, PRODUCTO.CODIGO
FROM PRODUCTO
WHERE PRODUCTO.CODIGO NOT IN (	SELECT CODIGOPRODUCTO 
							FROM DETALLEVENTA);

/* MOSTRAR POR CADA PRODUCTO CUANTOS SE HAN VENDIDO */
SELECT PRODUCTO.CODIGO, PRODUCTO.NOMBRE, COUNT(*) AS 'CANTIDAD DE VENTAS'
FROM PRODUCTO
WHERE PRODUCTO.CODIGO IN (	SELECT CODIGOPRODUCTO 
							FROM DETALLEVENTA) GROUP BY CODIGO;

/* MOSTRAR POR CADA TIPO DE PAGO, LA CANTIDAD DE VENTAS REALIZADAS */
Select COUNT(*) AS 'CANTIDAD DE VENTAS',TIPOPAGO.NOMBRE
From NOTAVENTA, TIPOPAGO
WHERE (IDTIPOPAGO=TIPOPAGO.ID) Group By IDTIPOPAGO;