/* CREACION DE TABLAS */

Create table CLIENTE
(
	CI INT NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    TELEFONO INT NOT NULL
);

CREATE TABLE FACTURA
(
	NRO SMALLINT NOT NULL PRIMARY KEY,
    FECHA DATE NOT NULL,
    MONTO SMALLINT NOT NULL,
    CICLIENTE INT NOT NULL,
    FOREIGN KEY (CICLIENTE) REFERENCES CLIENTE(CI) ON UPDATE CASCADE ON DELETE NO ACTION
);

CREATE TABLE DETALLEFACTURA
(
	NROF SMALLINT NOT NULL,
    ID TINYINT NOT NULL,
    PRIMARY KEY (NROF,ID),
    CANTIDAD TINYINT NOT NULL,
    PRECIO SMALLINT NOT NULL,
    CODIGOP VARCHAR(4) NOT NULL,
    FOREIGN KEY (CODIGOP) references PRODUCTO(CODIGO) ON UPDATE CASCADE ON DELETE NO ACTION
);

CREATE TABLE PRODUCTO
(
	CODIGO VARCHAR(4) NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(30) NOT NULL,
    PRECIOV SMALLINT NOT NULL,
    IDCATEGORIA SMALLINT NOT NULL,
    FOREIGN KEY (IDCATEGORIA) REFERENCES CATEGORIA(ID) ON UPDATE CASCADE ON DELETE NO ACTION
);

CREATE TABLE CATEGORIA
(
	ID SMALLINT PRIMARY KEY,
    DESCRIPCION VARCHAR(30) NOT NULL,
    IDPADRE SMALLINT,
    FOREIGN KEY (IDPADRE) REFERENCES CATEGORIA(ID)
);

