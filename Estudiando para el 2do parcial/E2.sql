/* MOSTRAR EL MONTO TOTAL INGRESADO POR LA VENTA DE PRODUCTOS DE TODAS LAS SUBCATEGORIAS DE LA CATEGORIA BEBIDAS NO ALCOHOLICAS */
SELECT SUM(DETALLEFACTURA.PRECIO * DETALLEFACTURA.CANTIDAD)
FROM  DETALLEFACTURA,PRODUCTO,CATEGORIA SUBCATEGORIA,CATEGORIA CATEGORIA
WHERE (CODIGOP = PRODUCTO.CODIGO) AND (IDCATEGORIA = SUBCATEGORIA.ID) AND (SUBCATEGORIA.IDPADRE = CATEGORIA.ID) AND (CATEGORIA.DESCRIPCION = 'BEBIDAS NO ALCOHOLICAS'); 

/* MOSTRAR LOS PRODUCTOS DE LA CATEOGORIA GASEOSA QUE SE HAN VENDIDO MAS DE UNA VEZ */
SELECT PRODUCTO.NOMBRE
FROM DETALLEFACTURA,PRODUCTO,CATEGORIA SUBCATEGORIA, CATEGORIA CATEGORIA
WHERE (CODIGOP = PRODUCTO.CODIGO) AND (IDCATEGORIA = SUBCATEGORIA.ID) AND (SUBCATEGORIA.IDPADRE = CATEGORIA.ID) AND SUBCATEGORIA.DESCRIPCION = 'GASEOSAS' GROUP BY DETALLEFACTURA.CODIGOP HAVING COUNT(*)>1;

